import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Reuse the microphone from the official Korean wordmark, without font rendering.
const officialLogo = readFileSync(
  new URL('../src/assets/brand/bulleoyo-logo-variant-a.svg', import.meta.url),
  'utf8',
)
const gradients = officialLogo.match(/<linearGradient\b[\s\S]*?<\/linearGradient>/g)
const microphone = officialLogo.match(
  /(<path\s+fill="url\(#indigo-soft\)"\s+filter="url\(#soft-lift\)"\s+d="M 638[\s\S]*?)<\/svg>/,
)
if (gradients?.length !== 2 || !microphone) {
  throw new Error('The official microphone geometry has changed; review the icon crop.')
}

// Keep the original head, grille, pink stand and gradients. The quiet background
// keeps the indigo visible on both light and dark browser tabs; no tiny shadow.
const svg = `<!-- Generated by pnpm gen:brand-icons from bulleoyo-logo-variant-a.svg. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" fill="none" role="img" aria-label="불러요">
  <title>불러요</title>
  <defs>
    ${gradients.join('\n    ')}
  </defs>
  <rect width="64" height="64" rx="14" fill="#F7F7FB" />
  <g transform="translate(-108.36 -17.98) scale(0.22)">
    ${microphone[1].replace(/\s*filter="url\(#soft-lift\)"/g, '').trim()}
  </g>
</svg>
`
writeFileSync(new URL('../public/brand/icon-app.svg', import.meta.url), svg)

if (!process.argv.includes('--svg-only')) {
  // playwright-core is already a project dev dependency. Use installed Chrome;
  // set BRAND_BROWSER_EXECUTABLE to use another Chromium executable locally.
  const { chromium } = await import('playwright-core')
  const browser = await chromium.launch({
    headless: true,
    ...(process.env.BRAND_BROWSER_EXECUTABLE
      ? { executablePath: process.env.BRAND_BROWSER_EXECUTABLE }
      : { channel: 'chrome' }),
  })
  try {
    for (const [size, filename] of [
      [32, 'icon-32.png'],
      [180, 'apple-touch-icon.png'],
    ]) {
      const page = await browser.newPage({ viewport: { width: size, height: size } })
      await page.setContent(
        `<html><head><style>html,body{margin:0;width:100%;height:100%}svg{display:block;width:100%;height:100%}</style></head><body>${svg}</body></html>`,
      )
      await page.screenshot({
        path: fileURLToPath(new URL(`../public/brand/${filename}`, import.meta.url)),
        omitBackground: true,
      })
      await page.close()
    }
  } finally {
    await browser.close()
  }
}
