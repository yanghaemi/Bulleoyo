import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import opentype from 'opentype.js'

// Build-time only. Pinned Fontsource ships WOFF (supported by opentype.js),
// so neither a system font nor a WOFF2 decoder can alter the generated logo.
const require = createRequire(import.meta.url)
const fontFile = require.resolve('@fontsource/montserrat/files/montserrat-latin-900-normal.woff')
const font = opentype.parse(readFileSync(fontFile))
const paths = [new opentype.Path(), new opentype.Path(), new opentype.Path()]
let index = 0
font.forEachGlyph('BULLEOYO', 0, 0, 200, { kerning: true }, (glyph, x, y, size) => {
  paths[index < 6 ? 0 : index - 5].extend(glyph.getPath(x, y, size))
  index += 1
})

const names = ['BULLEO_PATH', 'MIC_Y_PATH', 'MIC_O_PATH']
// opentype.js 2.0's toPathData can produce NaN for floating point coordinates.
// Serialize its finite, already positioned SVG commands without altering glyphs.
const coordinates = {
  M: ['x', 'y'],
  L: ['x', 'y'],
  Q: ['x1', 'y1', 'x', 'y'],
  C: ['x1', 'y1', 'x2', 'y2', 'x', 'y'],
  Z: [],
}
function serialize(path) {
  return path.commands
    .map((command) => {
      const values = coordinates[command.type].map((key) => {
        if (!Number.isFinite(command[key])) throw new Error(`Non-finite ${key}`)
        return Number(command[key].toFixed(2))
      })
      return `${command.type}${values.join(' ')}`
    })
    .join(' ')
}
const outlines = Object.fromEntries(paths.map((path, i) => [names[i], serialize(path)]))

// The official Korean letters have a 199-unit cap height and baseline at 338.
// One shared transform gives every English glyph that same cap and baseline;
// Montserrat's round-letter overshoot is intentionally preserved.
const scale = 199 / ((font.tables.os2.sCapHeight * 200) / font.unitsPerEm)
const left = 103
const x = left - paths[0].getBoundingBox().x1 * scale
const right = x + paths[2].getBoundingBox().x2 * scale
const koreanOffset = (left + right) / 2 - (103 + 723) / 2
const center = (path) => {
  const box = path.getBoundingBox()
  return { x: (box.x1 + box.x2) / 2, y: (box.y1 + box.y2) / 2 }
}
const yCenter = center(paths[1])
const oCenter = center(paths[2])
const round = (value) => Number(value.toFixed(6))
const geometry = {
  transform: `translate(${round(x)} 338) scale(${round(scale)})`,
  koreanOffset: round(koreanOffset),
  viewBoxWidth: round(right + 13 - 90),
  headEndX: round(x + oCenter.x * scale - (638 + koreanOffset)),
  headEndY: round(338 + oCenter.y * scale - 184.5),
  yStartX: round((638 + koreanOffset - x) / scale - yCenter.x),
  yStartY: round((285 - 338) / scale - yCenter.y),
}

if (process.argv.includes('--json')) {
  process.stdout.write(JSON.stringify({ outlines, geometry }))
} else {
  process.stdout.write('// Generated by pnpm gen:brand; do not hand-edit glyph commands.\n')
  for (const [name, path] of Object.entries(outlines)) {
    process.stdout.write(`const ${name} =\n  '${path}'\n\n`)
  }
  process.stdout.write(`const ENGLISH_GEOMETRY = ${JSON.stringify(geometry, null, 2)} as const\n`)
}
