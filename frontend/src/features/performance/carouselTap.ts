/**
 * 캐러셀 트랙의 탭 위치 → 이동 방향.
 *
 * ── 왜 있나 (2026-09-10) ─────────────────────────────────────────────
 * 좌우 화살표는 `hidden md:flex`라 **PC에만 있다.** 모바일에는 드래그와 점뿐인데, 옆 카드는
 * `pointerEvents: 'none'`이라 눌러도 아무 일이 없었다 — 화면 좌우 3분의 1이 죽은 자리였다.
 * 옆 카드는 "이전/다음"으로 읽히는 자리이므로 눌리는 게 맞다.
 *
 * 판정만 여기로 뽑아낸 이유 — 카드 폭(`CW`)이나 배율(`zoom`) 계산이 바뀌면 조용히 어긋나는데,
 * 컴포넌트 안에 있으면 DOM 없이는 확인할 방법이 없다. 숫자만 넣어 확인할 수 있게 나눠 둔다.
 */

/**
 * 드래그와 탭을 가르는 이동 거리(px).
 *
 * ⚠ **마우스 기준(6px)으로는 모바일에서 탭이 씹힌다**(MR !76 리뷰 지적). 손가락은 닿았다
 * 떨어지는 사이에 몇 px씩 흔들린다. Android의 터치 슬롭이 8dp, iOS가 대략 10pt이므로
 * 그 위쪽인 10px로 맞춘다. 이보다 짧게 민 것은 캐러셀도 어차피 제자리로 돌아오므로
 * (한 칸이 `GAP` 210px다) 탭으로 취급하는 편이 실제 동작과도 맞는다.
 *
 * 캡션 링크의 드래그 억제도 **같은 값을 쓴다** — 한쪽만 올리면 옆을 누르면 넘어가는데
 * 가운데를 누르면 안 열리는(또는 그 반대) 어긋난 손맛이 된다.
 *
 * 실기기에서 재보지 못했다(개발 환경이 데스크톱 브라우저다). 둔하게 느껴지면 이 값 하나만 올린다.
 */
export const TAP_SLOP = 10

/**
 * @param x         트랙 왼쪽 끝을 0으로 한 탭 위치(px, 뷰포트 기준)
 * @param y         트랙 위쪽 끝을 0으로 한 탭 위치(px)
 * @param width     트랙의 실제 폭(px). `zoom` 배율이 이미 반영된 값
 * @param height    트랙의 실제 높이(px)
 * @param cardWidth 중앙 카드 폭(트랙 좌표. 배율 적용 전)
 * @param fit       `zoom` 배율
 * @returns -1 이전 · 1 다음 · 0 아무것도 하지 않음
 */
export function tapDirection(
  x: number,
  y: number,
  width: number,
  height: number,
  cardWidth: number,
  fit: number,
): -1 | 0 | 1 {
  // ⚠ **좌표가 트랙 안에 있는지 먼저 확인한다**(MR !76 리뷰 지적).
  //
  // 키보드 Enter·스페이스로 생기는 가상 클릭은 좌표가 `(0, 0)`으로 온다. 모바일에서는 트랙이
  // 화면 왼쪽 끝에 붙어 `rect.left`가 0이라, x만 보면 `0`이 **정상적인 왼쪽 탭과 구별되지 않는다**
  // — 그대로 두면 키보드 사용자가 엉뚱하게 이전 칸으로 밀린다.
  //
  // 리뷰에서 제안받은 `detail === 0` 대신 좌표 범위를 보는 이유 — `UIEvent.detail`은 터치에서
  // 생긴 클릭에도 엔진에 따라 0이 올 수 있다. 그걸로 거르면 **일부 기기에서 이 기능이 통째로
  // 죽는데 그 사실이 드러나지 않는다.** 실기기가 없어 확인할 수 없으므로, 브라우저 구현에
  // 기대지 않는 쪽을 골랐다. 트랙은 헤더 아래에 있어 진짜 탭의 y가 0일 수 없다.
  if (x < 0 || x > width || y < 0 || y > height) return 0

  const mid = width / 2
  // 중앙 카드가 차지하는 폭의 절반. 트랙 좌표에 배율을 곱해 뷰포트 px로 맞춘다
  const halfCard = (cardWidth / 2) * fit
  if (x < mid - halfCard) return -1
  if (x > mid + halfCard) return 1
  // 중앙 카드 위 — 캡션 링크가 상세로 보내는 자리다. 여기서 넘기면 안 된다
  return 0
}
