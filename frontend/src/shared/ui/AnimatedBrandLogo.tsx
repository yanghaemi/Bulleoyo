function usePrefersReducedMotion() {
  const [reduced, setReduced] = useState(
    () =>
      typeof window !== 'undefined' &&
      typeof window.matchMedia === 'function' &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches,
  )

  useEffect(() => {
    if (typeof window.matchMedia !== 'function') return

    const query = window.matchMedia('(prefers-reduced-motion: reduce)')
    const sync = () => setReduced(query.matches)
    sync()
    query.addEventListener('change', sync)
    return () => query.removeEventListener('change', sync)
  }, [])

  return reduced
}

/**
 * 불러요 모션 로고.
 *
 * 공식 왼쪽 SVG와 빌드 시 생성한 영문 윤곽을 사용한다. 헤더는 문서마다 한 번
 * 자동 재생하고, SPA 재마운트에서는 완성형을 유지하며 클릭으로 다시 재생한다.
 */
export function AnimatedBrandLogo({ height = 28, mode = 'static', className, replayKey }: Props) {
  const rootRef = useRef<SVGSVGElement>(null)
  const previousReplayKey = useRef(replayKey)
  const reducedMotion = usePrefersReducedMotion()
  const [headerMotionState, setHeaderMotionState] = useState<HeaderMotionState>(() => {
    if (mode !== 'header' || reducedMotion) return 'complete'
    if (!hasSeenHeaderIntro()) return 'intro'
    return storedHeaderForm() === 'korean' ? 'korean' : 'complete'
  })
  const rawId = useId()
  const stableId = rawId.replace(/:/g, '')
  const indigoGradientId = `brand-indigo-${stableId}`
  const pinkGradientId = `brand-pink-${stableId}`
  const shadowId = `brand-shadow-${stableId}`
  const morphMaskId = `brand-morph-mask-${stableId}`

  useEffect(() => {
    if (previousReplayKey.current === replayKey) return
    previousReplayKey.current = replayKey
    if (replayKey === undefined || mode !== 'header' || reducedMotion) return
    setHeaderMotionState((current) => {
      if (current === 'complete') return 'return-reset'
      if (current === 'korean') return 'reset'
      return current
    })
  }, [replayKey, mode, reducedMotion])

  useEffect(() => {
    if (mode !== 'header') return

    if (reducedMotion) {
      setHeaderMotionState('complete')
      return
    }

    if (headerMotionState === 'reset' || headerMotionState === 'return-reset') {
      const frame = window.requestAnimationFrame(() => {
        // Commit the animation-free reset style before reapplying its CSS name.
        rootRef.current?.getBoundingClientRect()
        setHeaderMotionState(headerMotionState === 'reset' ? 'intro' : 'returning')
      })
      return () => window.cancelAnimationFrame(frame)
    }

    if (headerMotionState === 'complete' || headerMotionState === 'korean') {
      try {
        window.sessionStorage.setItem(
          HEADER_FORM_STORAGE_KEY,
          headerMotionState === 'korean' ? 'korean' : 'english',
        )
      } catch {
        // 시각 상태 저장 실패는 로고 자체의 렌더링을 막지 않는다.
      }
      return
    }

    if (headerMotionState !== 'intro' && headerMotionState !== 'returning') return

    if (headerMotionState === 'intro') {
      try {
        window.sessionStorage.setItem(
          HEADER_INTRO_STORAGE_KEY,
          String(window.performance.timeOrigin),
        )
      } catch {
        // 저장소가 막힌 환경에서도 현재 화면의 한 번 재생은 그대로 진행한다.
      }
    }

    const timer = window.setTimeout(
      () => setHeaderMotionState(headerMotionState === 'intro' ? 'complete' : 'korean'),
      headerMotionState === 'intro' ? BRAND_TIMING.totalMs : BRAND_TIMING.returnMs,
    )
    return () => window.clearTimeout(timer)
  }, [headerMotionState, mode, reducedMotion])

  const replay = () => {
    if (mode !== 'header' || reducedMotion) return
    setHeaderMotionState((current) => {
      if (current === 'complete') return 'return-reset'
      if (current === 'korean') return 'reset'
      return current
    })
  }

  return (
    <svg
      ref={rootRef}
      width={(height * ENGLISH_GEOMETRY.viewBoxWidth) / 260}
      height={height}
      viewBox={`90 95 ${ENGLISH_GEOMETRY.viewBoxWidth} 260`}
      fill="none"
      role="img"
      aria-label="불러요"
      data-motion-mode={mode}
      data-motion-duration={BRAND_TIMING.totalMs}
      data-header-motion-state={mode === 'header' ? headerMotionState : undefined}
      data-brand-form={headerMotionState === 'korean' ? 'korean' : 'english'}
      data-reduced-motion={reducedMotion ? 'true' : 'false'}
      data-logo-variant="variant-a-merged-stem"
      data-logo-geometry="normalized-v2"
      onClick={replayKey === undefined ? replay : undefined}
      style={
        {
          '--brand-duration': `${BRAND_TIMING.totalMs}ms`,
          '--brand-return-duration': `${BRAND_TIMING.returnMs}ms`,
          '--brand-head-end-x': `${ENGLISH_GEOMETRY.headEndX}px`,
          '--brand-head-end-y': `${ENGLISH_GEOMETRY.headEndY}px`,
          '--brand-y-start-x': `${ENGLISH_GEOMETRY.yStartX}px`,
          '--brand-y-start-y': `${ENGLISH_GEOMETRY.yStartY}px`,
        } as CSSProperties
      }
      className={['fx-brand', className].filter(Boolean).join(' ')}
    >
      <defs>
        <linearGradient id={indigoGradientId} x1="0" y1="0" x2="0.9" y2="1">
          <stop stopColor="#3E35E2" />
          <stop offset="0.55" stopColor="#3129DD" />
          <stop offset="1" stopColor="#4138E3" />
        </linearGradient>
        <linearGradient id={pinkGradientId} x1="0" y1="0" x2="0" y2="1">
          <stop stopColor="#D9468D" />
          <stop offset="1" stopColor="#C83D82" />
        </linearGradient>
        <filter
          id={shadowId}
          x="-12%"
          y="-12%"
          width="124%"
          height="128%"
          colorInterpolationFilters="sRGB"
        >
          <feDropShadow
            dx="0"
            dy="1.5"
            stdDeviation="1.7"
            floodColor="#20199B"
            floodOpacity="0.13"
          />
        </filter>
        <mask
          id={morphMaskId}
          x="540"
          y="90"
          width="200"
          height="200"
          maskUnits="userSpaceOnUse"
          maskContentUnits="userSpaceOnUse"
        >
          <rect x="540" y="90" width="200" height="200" fill="white" />
          <circle data-part="morph-aperture" cx="638" cy="184.5" r="35" fill="black" />
        </mask>
      </defs>

      <g transform={`translate(${ENGLISH_GEOMETRY.koreanOffset} 0)`}>
        <g data-part="ko-lockup">
          <path
            data-part="ko-word"
            d={WORDMARK_PATH}
            fill={`url(#${indigoGradientId})`}
            fillRule="evenodd"
            stroke={`url(#${indigoGradientId})`}
            strokeWidth="3.5"
            strokeLinecap="round"
            strokeLinejoin="round"
            filter={`url(#${shadowId})`}
          />
        </g>

        <g data-part="mic-stand" filter={`url(#${shadowId})`}>
          <g
            fill="none"
            stroke={`url(#${pinkGradientId})`}
            strokeWidth="15"
            strokeLinecap="round"
            strokeLinejoin="round"
          >
            <path d="M 584 250 C 588 271 604 288 638 299" />
            <path d="M 692 250 C 688 271 672 288 638 299" />
          </g>
          <rect x="627" y="292" width="22" height="34" rx="11" fill={`url(#${pinkGradientId})`} />
          <rect x="553" y="318" width="170" height="24" rx="12" fill={`url(#${pinkGradientId})`} />
        </g>

        <g data-part="morph-object" filter={`url(#${shadowId})`}>
          <g data-part="morph-shape">
            <circle
              data-part="morph-shell"
              cx="638"
              cy="184.5"
              r="79"
              fill={`url(#${indigoGradientId})`}
              mask={`url(#${morphMaskId})`}
            />
            <rect
              data-part="morph-grill"
              x="605"
              y="177.5"
              width="66"
              height="14"
              rx="7"
              fill="white"
            />
          </g>
        </g>
      </g>

      <g transform={ENGLISH_GEOMETRY.transform} filter={`url(#${shadowId})`}>
        <path data-part="english-word" d={BULLEO_PATH} fill={`url(#${indigoGradientId})`} />
        <path data-part="mic-y" d={MIC_Y_PATH} fill={`url(#${pinkGradientId})`} />
      </g>
    </svg>
  )
}
