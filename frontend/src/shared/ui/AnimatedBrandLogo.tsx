type HeaderMotionState =
  | 'reset'
  | 'intro'
  | 'complete'
  | 'return-reset'
  | 'returning'
  | 'korean'

const HEADER_INTRO_STORAGE_KEY = 'bulleoyo:header-intro-document'
const HEADER_FORM_STORAGE_KEY = 'bulleoyo:header-form'

function hasSeenHeaderIntro() {
  if (typeof window === 'undefined') return false

  try {
    return (
      window.sessionStorage.getItem(HEADER_INTRO_STORAGE_KEY) ===
      String(window.performance.timeOrigin)
    )
  } catch {
    return false
  }
}

function storedHeaderForm() {
  if (typeof window === 'undefined') return 'english'

  try {
    return window.sessionStorage.getItem(HEADER_FORM_STORAGE_KEY) === 'korean'
      ? 'korean'
      : 'english'
  } catch {
    return 'english'
  }
}

